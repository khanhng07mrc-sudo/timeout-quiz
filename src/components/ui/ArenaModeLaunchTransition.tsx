interface Props {
  isOpen: boolean;
  isReady?: boolean;
  mode: GameMode | string;
  modeName?: string;
  sourceRect?: { top: number; left: number; width: number; height: number } | null;
  onComplete?: () => void;
}

const getModeVideoPath = (m: string) => {
  const norm = (m || "CLASSIC").toUpperCase();
  if (norm.includes("CARO")) return "/transitions/grid_caro.webm";
  if (norm.includes("MYSTERY") || norm.includes("QUEST")) return "/transitions/mystery_quest.webm";
  if (norm.includes("BUZZ") || norm.includes("SPEED") || norm.includes("RACE")) return "/transitions/speed_race.webm";
  if (norm.includes("TOWER") || norm.includes("DEFENSE") || norm.includes("ELIMINATION")) return "/transitions/tower_defense.webm";
  if (norm.includes("BATTLE") || norm.includes("ROYALE") || norm.includes("TOURNAMENT")) return "/transitions/battle_royale.webm";
  if (norm.includes("BOSS") || norm.includes("RAID")) return "/transitions/boss_raid.webm";
  if (norm.includes("GOLD") || norm.includes("MINE") || norm.includes("WAGER")) return "/transitions/gold_mine.webm";
  if (norm.includes("AUCTION") || norm.includes("STEALTH") || norm.includes("DICE")) return "/transitions/auction_stealth.webm";
  return "/transitions/classic.webm";
};

// ── 3D Canvas Spinning Wheel for Magic Wheel Mode (Zero Black Box, Pure 60fps) ──
function MagicWheel3DCanvasTransition({ isExpanded, isOutro }: { isExpanded: boolean; isOutro: boolean }) {
  const canvasRef = useRef<HTMLCanvasElement | null>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;

    let animId: number;
    const startTime = performance.now();
    const duration = 1400; // 1.4s launch duration

    // 24 sectors matching official VTV3 Magic Wheel
    const SECTORS = [
      { label: "500", color: "#e11d48", text: "#ffffff" },
      { label: "300", color: "#2563eb", text: "#ffffff" },
      { label: "MẤT LƯỢT", color: "#334155", text: "#f8fafc" },
      { label: "700", color: "#d97706", text: "#ffffff" },
      { label: "200", color: "#059669", text: "#ffffff" },
      { label: "THÊM LƯỢT", color: "#0284c7", text: "#ffffff" },
      { label: "400", color: "#7c3aed", text: "#ffffff" },
      { label: "MẤT ĐIỂM", color: "#1e293b", text: "#f87171" },
      { label: "900", color: "#ea580c", text: "#ffffff" },
      { label: "100", color: "#0d9488", text: "#ffffff" },
      { label: "CHIA ĐÔI", color: "#4f46e5", text: "#ffffff" },
      { label: "600", color: "#db2777", text: "#ffffff" },
      { label: "300", color: "#2563eb", text: "#ffffff" },
      { label: "NHÂN ĐÔI", color: "#ca8a04", text: "#000000" },
      { label: "200", color: "#059669", text: "#ffffff" },
      { label: "MAY MẮN", color: "#eab308", text: "#000000" },
      { label: "800", color: "#9333ea", text: "#ffffff" },
      { label: "500", color: "#e11d48", text: "#ffffff" },
      { label: "PHẦN THƯỞNG", color: "#c026d3", text: "#ffffff" },
      { label: "100", color: "#0d9488", text: "#ffffff" },
      { label: "ĐỔI ĐIỂM", color: "#0891b2", text: "#ffffff" },
      { label: "400", color: "#7c3aed", text: "#ffffff" },
      { label: "BẢO HIỂM", color: "#16a34a", text: "#ffffff" },
      { label: "1000", color: "#f59e0b", text: "#000000" },
    ];

    const numSectors = SECTORS.length;
    const arc = (Math.PI * 2) / numSectors;

    // Spark particles generated by needle friction
    const sparks: Array<{ x: number; y: number; vx: number; vy: number; life: number; color: string }> = [];

    const render = (time: number) => {
      const elapsed = time - startTime;
      const progress = Math.min(1, elapsed / duration);

      // Deceleration curve (spins fast initially, slows down smoothly)
      const ease = 1 - Math.pow(1 - progress, 3);
      const totalRotations = 5.5; // Spins 5.5 full turns
      const currentAngle = ease * (totalRotations * Math.PI * 2);

      const w = canvas.width;
      const h = canvas.height;
      const cx = w / 2;
      const cy = h / 2 + 15;
      const radius = 230;

      ctx.clearRect(0, 0, w, h);

      ctx.save();
      // 3D Isometric Tilt Perspective
      ctx.translate(cx, cy);
      ctx.scale(1, 0.72); // Elliptical 3D tilt

      // Outer Deep Chrome Rim Shadow
      ctx.beginPath();
      ctx.arc(0, 18, radius + 18, 0, Math.PI * 2);
      ctx.fillStyle = "rgba(0, 0, 0, 0.65)";
      ctx.fill();

      // Metallic Beveled Rim
      const rimGrad = ctx.createRadialGradient(0, 0, radius - 4, 0, 0, radius + 14);
      rimGrad.addColorStop(0, "#334155");
      rimGrad.addColorStop(0.5, "#cbd5e1");
      rimGrad.addColorStop(0.85, "#94a3b8");
      rimGrad.addColorStop(1, "#1e293b");
      ctx.beginPath();
      ctx.arc(0, 0, radius + 14, 0, Math.PI * 2);
      ctx.fillStyle = rimGrad;
      ctx.fill();

      // Outer Gold Neon Ring
      ctx.beginPath();
      ctx.arc(0, 0, radius + 2, 0, Math.PI * 2);
      ctx.lineWidth = 4;
      ctx.strokeStyle = "#fbbf24";
      ctx.stroke();

      // Rotating Wheel Slices
      ctx.save();
      ctx.rotate(currentAngle);

      for (let i = 0; i < numSectors; i++) {
        const sector = SECTORS[i];
        const a1 = i * arc;
        const a2 = a1 + arc;

        // Sector Wedge
        ctx.beginPath();
        ctx.moveTo(0, 0);
        ctx.arc(0, 0, radius, a1, a2);
        ctx.closePath();
        ctx.fillStyle = sector.color;
        ctx.fill();

        // Sector Divider Stroke
        ctx.lineWidth = 2;
        ctx.strokeStyle = "rgba(255, 255, 255, 0.4)";
        ctx.stroke();

        // Slice Label Text
        ctx.save();
        ctx.rotate(a1 + arc / 2);
        ctx.textAlign = "right";
        ctx.textBaseline = "middle";
        ctx.font = "900 13px 'Inter', sans-serif";
        ctx.fillStyle = sector.text;
        ctx.shadowColor = "rgba(0, 0, 0, 0.85)";
        ctx.shadowBlur = 4;
        ctx.fillText(sector.label, radius - 24, 0);
        ctx.restore();
      }

      // Outer Gold Metallic Pegs (Pins)
      for (let i = 0; i < numSectors; i++) {
        const pegAngle = i * arc;
        const px = Math.cos(pegAngle) * (radius - 5);
        const py = Math.sin(pegAngle) * (radius - 5);

        ctx.beginPath();
        ctx.arc(px, py, 4.5, 0, Math.PI * 2);
        const pegGrad = ctx.createRadialGradient(px - 1, py - 1, 1, px, py, 4.5);
        pegGrad.addColorStop(0, "#fffbeb");
        pegGrad.addColorStop(0.4, "#f59e0b");
        pegGrad.addColorStop(1, "#78350f");
        ctx.fillStyle = pegGrad;
        ctx.fill();
        ctx.strokeStyle = "rgba(0, 0, 0, 0.6)";
        ctx.lineWidth = 1;
        ctx.stroke();
      }

      ctx.restore(); // Restore wheel rotation

      // Central 3D Metallic Chrome Hub
      const hubRadius = 62;
      const hubGrad = ctx.createRadialGradient(0, -10, 5, 0, 0, hubRadius);
      hubGrad.addColorStop(0, "#f8fafc");
      hubGrad.addColorStop(0.3, "#e2e8f0");
      hubGrad.addColorStop(0.7, "#64748b");
      hubGrad.addColorStop(1, "#0f172a");

      ctx.beginPath();
      ctx.arc(0, 0, hubRadius, 0, Math.PI * 2);
      ctx.fillStyle = hubGrad;
      ctx.fill();
      ctx.lineWidth = 3;
      ctx.strokeStyle = "#fbbf24";
      ctx.stroke();

      // Inner Hub Glowing Emblem
      ctx.beginPath();
      ctx.arc(0, 0, hubRadius - 14, 0, Math.PI * 2);
      ctx.fillStyle = "#0f172a";
      ctx.fill();
      ctx.lineWidth = 2;
      ctx.strokeStyle = "#38bdf8";
      ctx.stroke();

      // Hub Star / Starburst Emblem
      ctx.fillStyle = "#f59e0b";
      ctx.font = "900 22px 'Inter', sans-serif";
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.fillText("★", 0, 0);

      ctx.restore(); // Restore isometric tilt

      // Top 3D Chrome Pointer / Needle (Placed at top edge)
      const needleTopY = cy - radius * 0.72 - 8;
      const needleAngle = Math.sin(currentAngle * 24) * 0.12 * (1 - progress * 0.5); // Needle vibrates on pegs

      ctx.save();
      ctx.translate(cx, needleTopY);
      ctx.rotate(needleAngle);

      // Needle Shadow
      ctx.beginPath();
      ctx.moveTo(-14, -20);
      ctx.lineTo(14, -20);
      ctx.lineTo(0, 28);
      ctx.closePath();
      ctx.fillStyle = "rgba(0, 0, 0, 0.4)";
      ctx.fill();

      // Needle Metallic Body
      const needleGrad = ctx.createLinearGradient(-12, 0, 12, 0);
      needleGrad.addColorStop(0, "#f59e0b");
      needleGrad.addColorStop(0.3, "#fef08a");
      needleGrad.addColorStop(0.7, "#d97706");
      needleGrad.addColorStop(1, "#78350f");

      ctx.beginPath();
      ctx.moveTo(-12, -22);
      ctx.lineTo(12, -22);
      ctx.lineTo(0, 26);
      ctx.closePath();
      ctx.fillStyle = needleGrad;
      ctx.fill();
      ctx.lineWidth = 1.5;
      ctx.strokeStyle = "#ffffff";
      ctx.stroke();

      // Needle Pivot Hub
      ctx.beginPath();
      ctx.arc(0, -22, 9, 0, Math.PI * 2);
      ctx.fillStyle = "#e2e8f0";
      ctx.fill();
      ctx.stroke();

      // Spark generation on peg hit
      if (Math.abs(needleAngle) > 0.08 && sparks.length < 35 && progress < 0.8) {
        for (let s = 0; s < 2; s++) {
          sparks.push({
            x: cx + (Math.random() - 0.5) * 8,
            y: needleTopY + 24,
            vx: (Math.random() - 0.5) * 4,
            vy: Math.random() * -3 - 1,
            life: 1,
            color: Math.random() > 0.5 ? "#fef08a" : "#38bdf8",
          });
        }
      }

      ctx.restore();

      // Draw and update sparks
      for (let s = sparks.length - 1; s >= 0; s--) {
        const sp = sparks[s];
        sp.x += sp.vx;
        sp.y += sp.vy;
        sp.life -= 0.04;
        if (sp.life <= 0) {
          sparks.splice(s, 1);
          continue;
        }
        ctx.beginPath();
        ctx.arc(sp.x, sp.y, 2.5 * sp.life, 0, Math.PI * 2);
        ctx.fillStyle = sp.color;
        ctx.shadowColor = sp.color;
        ctx.shadowBlur = 6;
        ctx.fill();
      }

      if (progress < 1) {
        animId = requestAnimationFrame(render);
      }
    };

    animId = requestAnimationFrame(render);
    return () => cancelAnimationFrame(animId);
  }, []);

  return (
    <div
      className="relative flex items-center justify-center pointer-events-none will-change-transform"
      style={{
        transform: isExpanded ? "scale(1)" : "scale(0.85)",
        transition: "transform 260ms cubic-bezier(0.16, 1, 0.3, 1), opacity 280ms ease-out",
        opacity: isOutro ? 0 : 1,
      }}
    >
      {/* Golden Aura Glow */}
      <div className="absolute w-[480px] h-[480px] rounded-full pointer-events-none blur-3xl opacity-40 bg-gradient-to-tr from-amber-500/35 via-yellow-400/20 to-cyan-500/25" />
      <canvas
        ref={canvasRef}
        width={560}
        height={560}
        className="w-[340px] h-[340px] sm:w-[460px] sm:h-[460px] object-contain drop-shadow-[0_15px_35px_rgba(0,0,0,0.65)]"
      />
    </div>
  );
}

// ── Transparent WebM Video Canvas Renderer (Eliminates Chrome/Edge Black Box) ──
function TransparentWebMCanvasVideo({
  videoSrc,
  isExpanded,
  isOutro,
  onEnded,
}: {
  videoSrc: string;
  isExpanded: boolean;
  isOutro: boolean;
  onEnded: () => void;
}) {
  const videoRef = useRef<HTMLVideoElement | null>(null);
  const canvasRef = useRef<HTMLCanvasElement | null>(null);

  useEffect(() => {
    const video = videoRef.current;
    const canvas = canvasRef.current;
    if (!video || !canvas) return;

    const ctx = canvas.getContext("2d", { willReadFrequently: true });
    if (!ctx) return;

    let animId: number;
    let isActive = true;

    const processFrame = () => {
      if (!isActive) return;

      if (video.readyState >= 2 && !video.paused && !video.ended) {
        const cw = canvas.width;
        const ch = canvas.height;

        // Draw current video frame to canvas
        ctx.drawImage(video, 0, 0, cw, ch);

        // Real-time Luminance Alpha Keying: eliminates pure black background
        try {
          const imgData = ctx.getImageData(0, 0, cw, ch);
          const d = imgData.data;
          const len = d.length;

          for (let i = 0; i < len; i += 4) {
            const r = d[i];
            const g = d[i + 1];
            const b = d[i + 2];
            const maxVal = Math.max(r, g, b);

            // True black / dark background gets stripped to 100% transparent alpha
            if (maxVal < 18) {
              d[i + 3] = 0;
            } else if (maxVal < 70) {
              // Smooth gradient anti-aliasing on edge transitions
              d[i + 3] = Math.round((d[i + 3] * (maxVal - 18)) / 52);
            }
          }

          ctx.putImageData(imgData, 0, 0);
        } catch {
          // Canvas security fallback
        }
      }

      animId = requestAnimationFrame(processFrame);
    };

    video.currentTime = 0;
    video
      .play()
      .then(() => {
        animId = requestAnimationFrame(processFrame);
      })
      .catch(() => {});

    return () => {
      isActive = false;
      cancelAnimationFrame(animId);
    };
  }, [videoSrc]);

  return (
    <div
      className="relative flex items-center justify-center pointer-events-none will-change-transform"
      style={{
        transform: isExpanded ? "scale(1)" : "scale(0.9)",
        transition: "transform 260ms cubic-bezier(0.16, 1, 0.3, 1), opacity 280ms ease-out",
        opacity: isOutro ? 0 : 1,
      }}
    >
      {/* Hologram Aura Glow */}
      <div className="absolute w-[440px] h-[440px] rounded-full pointer-events-none blur-3xl opacity-35 bg-gradient-to-tr from-cyan-500/30 to-purple-500/25" />

      {/* Hidden offscreen HTML5 Video supplying frames */}
      <video
        ref={videoRef}
        src={videoSrc}
        muted
        playsInline
        preload="auto"
        onEnded={onEnded}
        className="hidden"
      />

      {/* Hardware Rasterized Canvas (100% transparent background) */}
      <canvas
        ref={canvasRef}
        width={640}
        height={360}
        className="w-full max-w-[640px] h-auto object-contain pointer-events-none drop-shadow-[0_10px_30px_rgba(0,0,0,0.5)]"
      />
    </div>
  );
}

export default function ArenaModeLaunchTransition({
  isOpen,
  isReady = false,
  mode,
  modeName,
  sourceRect,
  onComplete,
}: Props) {
  const [mounted, setMounted] = useState(false);
  const [phase, setPhase] = useState<"idle" | "loading" | "outro">("idle");
  const [isExpanded, setIsExpanded] = useState(false);
  const onCompleteRef = useRef(onComplete);
  onCompleteRef.current = onComplete;

  const timerOutroRef = useRef<NodeJS.Timeout | null>(null);
  const timerDoneRef = useRef<NodeJS.Timeout | null>(null);
  const timerFallbackRef = useRef<NodeJS.Timeout | null>(null);
  const timerExpandRef = useRef<NodeJS.Timeout | null>(null);
  const hasTriggeredLaunchRef = useRef<boolean>(false);

  useEffect(() => {
    setMounted(true);
  }, []);

  const triggerOutro = useCallback(() => {
    setPhase((prev) => {
      if (prev === "outro" || prev === "idle") return prev;
      if (timerDoneRef.current) clearTimeout(timerDoneRef.current);
      timerDoneRef.current = setTimeout(() => {
        setPhase("idle");
        setIsExpanded(false);
        hasTriggeredLaunchRef.current = false;
        if (onCompleteRef.current) {
          onCompleteRef.current();
        }
      }, 280);
      return "outro";
    });
  }, []);

  useEffect(() => {
    if (!isOpen) {
      hasTriggeredLaunchRef.current = false;
      if (timerOutroRef.current) clearTimeout(timerOutroRef.current);
      if (timerDoneRef.current) clearTimeout(timerDoneRef.current);
      if (timerFallbackRef.current) clearTimeout(timerFallbackRef.current);
      if (timerExpandRef.current) clearTimeout(timerExpandRef.current);
      setPhase("idle");
      setIsExpanded(false);
      return;
    }

    if (hasTriggeredLaunchRef.current) return;
    hasTriggeredLaunchRef.current = true;

    setPhase("loading");
    setIsExpanded(false);

    timerExpandRef.current = setTimeout(() => {
      setIsExpanded(true);
    }, 25);

    // Phát âm thanh chuyển cảnh thời lượng 1.25s bằng Web Audio synthesizer (0ms latency, không nghẽn audio)
    // Cửa sổ chính (top window, kể cả trong Sandbox) phát âm thanh; chỉ ngăn chặn iframe con lặp âm
    const isChildIframe = typeof window !== "undefined" && window.self !== window.top;

    if (!isChildIframe) {
      const modeStr = String(mode || "").toUpperCase();
      transitionSoundEngine.playTransitionSfx(modeStr);
    }

    // Thời gian transition mượt mà (1.25s)
    timerOutroRef.current = setTimeout(() => {
      triggerOutro();
    }, 1250);

    timerFallbackRef.current = setTimeout(() => {
      triggerOutro();
    }, 5000);

    return () => {
      if (timerOutroRef.current) clearTimeout(timerOutroRef.current);
      if (timerFallbackRef.current) clearTimeout(timerFallbackRef.current);
      if (timerExpandRef.current) clearTimeout(timerExpandRef.current);
    };
  }, [isOpen, mode, triggerOutro]);

  if (!isOpen && phase === "idle") return null;
  if (!mounted || typeof document === "undefined") return null;

  const currentMode = String(mode || "CLASSIC").toUpperCase();
  const isOutro = phase === "outro";
  const isMagicWheel = currentMode === "MAGIC_WHEEL" || currentMode.includes("WHEEL");
  const videoSrc = getModeVideoPath(currentMode);

  return createPortal(
    <div
      aria-hidden="true"
      style={{
        position: "fixed",
        top: 0,
        left: 0,
        width: "100vw",
        height: "100vh",
        zIndex: 99999,
        willChange: "opacity",
      }}
      className={`pointer-events-none overflow-hidden flex items-center justify-center select-none transition-opacity duration-300 ${
        isOutro ? "opacity-0" : "opacity-100"
      }`}
    >
      {/* ── 1. VẦNG HÀO QUANG RADIAL AURA TRUNG TÂM (100% trong suốt bên ngoài) ── */}
      <div
        className={`absolute inset-0 pointer-events-none transition-opacity duration-400 ${
          isOutro ? "opacity-0" : "opacity-100"
        }`}
        style={{
          background: isMagicWheel
            ? "radial-gradient(circle at 50% 48%, rgba(245,158,11,0.22) 0%, rgba(147,51,234,0.12) 35%, transparent 68%)"
            : "radial-gradient(circle at 50% 48%, rgba(6,182,212,0.20) 0%, rgba(147,51,234,0.10) 35%, transparent 65%)",
        }}
      />

      {/* ── 2. KHỐI HIỂN THỊ CHÍNH (3D Canvas Wheel hoặc Video Canvas với Keying không viền đen) ── */}
      <div className="absolute inset-0 pointer-events-none flex items-center justify-center">
        {isMagicWheel ? (
          <MagicWheel3DCanvasTransition isExpanded={isExpanded} isOutro={isOutro} />
        ) : (
          <TransparentWebMCanvasVideo
            videoSrc={videoSrc}
            isExpanded={isExpanded}
            isOutro={isOutro}
            onEnded={triggerOutro}
          />
        )}
      </div>

      {/* ── 3. THÔNG TIN TIÊU ĐỀ & TIẾN TRÌNH KHỞI TẠO ĐẤU TRƯỜNG CHUẨN ESPORTS ── */}
      <div
        className="absolute bottom-12 sm:bottom-16 z-20 flex flex-col items-center justify-center text-center transition-all duration-300 ease-out will-change-transform pointer-events-none max-w-md mx-auto px-4"
        style={{
          transform: isOutro ? "scale(0.9) translateY(12px)" : "scale(1) translateY(0)",
          opacity: isOutro ? 0 : 1,
        }}
      >
        <div className={`inline-flex items-center gap-2 px-4 py-1.5 rounded-full border text-[11px] font-mono font-black tracking-widest uppercase shadow-[0_4px_12px_rgba(0,0,0,0.5)] ${
          isMagicWheel
            ? "bg-amber-950/80 border-amber-400/40 text-amber-300"
            : "bg-cyan-950/80 border-cyan-400/40 text-cyan-300"
        }`}>
          <span className={`w-2 h-2 rounded-full animate-ping ${isMagicWheel ? "bg-amber-400" : "bg-cyan-400"}`} />
          {isOutro ? "MỞ CỔNG ĐẤU TRƯỜNG" : "KHỞI ĐỘNG ĐẤU TRƯỜNG ARENA"}
        </div>
        <h2 className={`mt-2 text-3xl sm:text-4xl font-black text-transparent bg-clip-text tracking-tight drop-shadow-[0_4px_24px_rgba(34,211,238,0.4)] ${
          isMagicWheel
            ? "bg-gradient-to-r from-amber-200 via-yellow-100 to-orange-300"
            : "bg-gradient-to-r from-white via-cyan-100 to-purple-200"
        }`}>
          {modeName || (isMagicWheel ? "Magic Wheel" : currentMode)}
        </h2>
        <p className="mt-1 text-xs text-slate-400 font-medium tracking-wide">
          {isOutro
            ? "Bàn đấu đã sẵn sàng · Đang mở màn hé lộ giao diện thi đấu..."
            : "Đang kết nối hệ thống · Chuẩn bị màn chiếu & thiết bị thí sinh..."}
        </p>

        {/* Thanh tiến trình lượng tử sắc nét */}
        <div className="mt-3.5 w-56 h-1.5 bg-white/10 rounded-full overflow-hidden border border-white/20 p-0.5 relative shadow-[0_0_15px_rgba(6,182,212,0.2)]">
          <div
            className={`h-full rounded-full transition-all ${
              isMagicWheel
                ? "bg-gradient-to-r from-amber-500 via-orange-400 to-yellow-300"
                : "bg-gradient-to-r from-purple-500 via-cyan-400 to-emerald-400"
            } ${isOutro ? "w-full duration-150" : "w-3/4 animate-pulse duration-500"}`}
          />
        </div>
      </div>
    </div>,
    document.body
  );
}
